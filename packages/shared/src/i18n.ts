export const MESSAGES: Record<Lang, Messages> = {
  'sr-Cyrl': srCyrl,
  'sr-Latn': srLatn,
  en,
  ru,
};

/** Look up a message, interpolating {placeholders}. Falls back to the default language. */
export function t(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const raw = MESSAGES[lang]?.[key] ?? MESSAGES[DEFAULT_LANG][key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}

/** Bind a language once, for components and PDF generators. */
export const translator = (lang: Lang) => (key: string, vars?: Record<string, string | number>) => t(lang, key, vars);

export type Translate = ReturnType<typeof translator>;
